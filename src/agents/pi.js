/**
 * Pi has no hook entries in a settings file. Instead it loads extensions —
 * TypeScript modules that subscribe to events programmatically:
 *
 *   export default function (pi) { pi.on("session_start", async () => {}) }
 *
 * so this adapter generates a whole extension file rather than editing a
 * config. The file-ownership rules that follow from that are shared with the
 * other generated-file agent (see generated-file.js); what lives here is the
 * template, the events and where Pi looks for them.
 *
 * Extensions run on Node (loaded through jiti), so the generated file can spawn
 * the same hook shim the other agents use — which keeps binding, volume and
 * playback resolution in exactly one place.
 */

export const EXTENSION_FILENAME = 'agentfx.ts';

/**
 * Pi's own override: "Override the config directory; default is ~/.pi/agent".
 * Note it points at the agent directory, not at ~/.pi.
 */
export const configDir = envDir('PI_CODING_AGENT_DIR', () =>
  path.join(os.homedir(), '.pi', 'agent')
);

export function defaultSettingsPath() {
  return path.join(configDir(), 'extensions', EXTENSION_FILENAME);
}

export function detect() {
  return fs.existsSync(configDir());
}

