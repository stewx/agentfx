/* ---------------- the generated extension ---------------- */

/** Marks the file as ours, so we never overwrite one somebody else wrote. */
export const MARKER = 'Generated by agentfx';

/** Reads back the events a generated extension subscribes to. */
export function parseEvents(source) {
  return parseArrayConst(source, 'AGENTFX_EVENTS');
}

/** Reads back the argv a generated extension will spawn. Null if unreadable. */
export function parseCommand(source) {
  const argv = parseArrayConst(source, 'AGENTFX_COMMAND');
  return argv.length ? argv : null;
}

export function buildExtension(eventIdList, argv) {
  const header = generatedHeader({
    marker: MARKER,
    summary: '// Plays a sound effect when Pi emits one of the events bound in the agentfx UI.',
    agentId: id,
    constants: [
      `const AGENTFX_EVENTS = ${JSON.stringify(eventIdList)};`,
      `const AGENTFX_COMMAND = ${JSON.stringify(argv)};`
    ].join('\n')
  });

  return `${header}
export default function (pi) {
  for (const event of AGENTFX_EVENTS) {
    // Returns nothing: these are observation-only events, and a handler that
    // returned a value could change how Pi behaves.
    pi.on(event, async () => {
      play(event);
    });
  }
}
`;
}

/** How generated-file.js recognises and reads back the files this agent owns. */
const SPEC = {
  marker: MARKER,
  noun: 'extension',
  build: buildExtension,
  parseEvents,
  parseCommand
};

export const { eventIds, resolveTargetPath, listTargets, sync, status, inspect } =
  makeGeneratedAdapter({ id, events, scopes: SCOPES, defaultSettingsPath, detect, spec: SPEC });
